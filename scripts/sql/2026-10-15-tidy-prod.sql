-- ⚠️ 一次性生产库整理（2026-10-15）⚠️
--
-- 用途：内测期数据整理。**执行前已经用户逐项确认**：
--   · 评论重排（id 7 → 3，消除删除留下的空档）
--   · 审计清空（用户确认"都是测试"）
--   · 限流桶清空
--   · 过期验证码清空
--   · **sessions 不清**（保留登录状态）
--   · **users 不动**（3 个真实用户，id/public_no 已连续）
--   · **review_note_presets 不动**（是正常配置）
--
-- 执行：
--   npx wrangler d1 execute myrzg-comments --remote --file=./scripts/sql/2026-10-15-tidy-prod.sql
--
-- 为什么不能只靠 AUTOINCREMENT 自己收敛：它的语义就是**永不复用**。
-- 删了 3/4/5/6 之后，新评论从 7 继续，空档永久保留 —— 要消除只能显式重排。

-- ============================================================
-- ① 评论重排：把 id=7 挪到 id=3，消除空档
--
-- 🔴 两个守卫，缺一不可：
--   `NOT EXISTS (id=3)` —— 防撞主键。重复执行本脚本时，第一次已把 7 改成 3，
--     第二次 `WHERE id=7` 匹配不到行 → 天然幂等；但若中间又插了新评论占了 3，
--     这一条会**拒绝执行而不是报主键冲突**。
--
--   `WHERE id=7` 精确指定 —— 不做"全部重编号"。全量重编号要按序更新每一条，
--     且过程中会与既有 id 撞车（SQLite 无延迟约束），风险远大于收益。
--
-- 安全性核实（执行前已查）：
--   · `comments.parent_id` 全为 NULL  → 无回复链会因此错位
--   · `users.replies_read_id` 全为 NULL → 无未读基准指向旧 id
--   · 无外键、无触发器
--   · `admin_audit` 里指向 comment 的记录**即将被清空**，不会留下指向旧 id 的历史
-- ============================================================
UPDATE comments SET id = 3
 WHERE id = 7
   AND NOT EXISTS (SELECT 1 FROM comments WHERE id = 3);

-- ============================================================
-- ② 评论水位 = 实际最大 id
--
-- 从数据推导而不是写死 `3`：若①因守卫未执行（例如 id=3 已被占），
-- 水位也应等于真实最大值，而不是一个假设值。
-- ============================================================
UPDATE sqlite_sequence
   SET seq = (SELECT COALESCE(MAX(id), 0) FROM comments)
 WHERE name = 'comments';

-- ============================================================
-- ③ 审计清空 + 水位归零
--
-- 用户确认 8 条记录**全部**是自测（comment_hide/show/delete）。
-- 审计是历史账本，正常不该清 —— 这里清了，因为它们是开发期产生的，
-- 不代表任何真实运营记录。
--
-- 🔴 清了数据就要清水位：否则下一条审计从 9 开始，
--    而后台显示的审计条数从 1 开始，编号与条数对不上（正是本次要消除的现象）。
-- ============================================================
DELETE FROM admin_audit;
DELETE FROM sqlite_sequence WHERE name = 'admin_audit';

-- ============================================================
-- ④ 限流桶全清
--
-- 36 条，全是开发期各 IP 的小时/日桶 —— 永远不会再被读取。
-- ⚠️ 副作用：等于**重置所有 IP 的限流额度**。限流是防刷的软闸门，
--    重置只会在接下来几分钟内允许略多的请求，无安全影响。
--
-- 注：本轮同时修了"限流桶从不清理"的缺陷（见 functions/api/[[path]].js
--     的 pruneExpiredRateLimits），以后会每 10 分钟自动清一次旧的。
-- ============================================================
DELETE FROM rate_limits;

-- ============================================================
-- ⑤ 验证码清空
--
-- 它本来就有过期自清（出题时 `DELETE WHERE expires_at <= now`），
-- 所以这里只是把"当前可能还活着的 1 条"也清掉 —— 那条是开发期出的题。
-- ============================================================
DELETE FROM captchas;

-- ============================================================
-- 结果核对
-- ============================================================
SELECT '评论（应为 1,2,3）' AS note, id, nick, user_id FROM comments ORDER BY id;
SELECT '评论水位（应为 3）' AS note, seq FROM sqlite_sequence WHERE name = 'comments';
SELECT '审计条数（应为 0）' AS note, COUNT(*) AS n FROM admin_audit;
SELECT '限流桶（应为 0）' AS note, COUNT(*) AS n FROM rate_limits;
SELECT '验证码（应为 0）' AS note, COUNT(*) AS n FROM captchas;
SELECT '用户（应为 3，不变）' AS note, COUNT(*) AS n FROM users;
SELECT '会话（应为 3，不清）' AS note, COUNT(*) AS n FROM sessions;
