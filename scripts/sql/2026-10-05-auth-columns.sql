-- 命令：
--   npx wrangler d1 execute myrzg-comments --remote --file=./scripts/sql/2026-10-05-auth-columns.sql
--
-- ===============================================================
-- 本文件只有一条语句，所以它的失败模式也只有一个：
--
--   `duplicate column name: user_id`
--     → 这一列已经在了。**要么你重复跑了，要么这个库本来就迁过。**
--       两种情况下都无事可做，直接进第 3 步。
-- ===============================================================
--
-- ---------------------------------------------------------------
-- 🔴 为什么只留一条语句
--
-- 早先这里还有第二条：`ALTER TABLE users ADD COLUMN pw_salt`。
-- 但它**对生产库是多余的动作** —— `users` 是第 1 步刚创建的，
-- 建表语句里本来就带 `pw_salt`。留着它的唯一后果是：运维在生产上跑完
-- 这一步会看到一条 `duplicate column name: pw_salt` 报错。
--
-- 迁移脚本"报了一条错但其实成功了"是最坏的形态：操作者无法判断
-- 是"预期内的重复"还是"真的炸了"，于是要么不敢往下走，要么忽略真问题。
-- 所以把它挪到文件末尾**注释掉**，只留给真正需要它的场景（见下）。
-- ---------------------------------------------------------------

-- 【唯一的正式步骤】评论挂账号。
--   可空：账号体系**之前**的匿名评论 `user_id` 为 NULL，不该被硬塞归属。
--   存量评论在界面上照常显示，只是不挂在任何账号下、
--   也不会出现在任何人的「我的评论」里（那本来就不是他们发的）。
ALTER TABLE comments ADD COLUMN user_id INTEGER DEFAULT NULL;

-- 自检：这一列应该在了
SELECT '第 2 步自检：comments.user_id 应为 1' AS note;
SELECT COUNT(*) AS present FROM pragma_table_info('comments') WHERE name = 'user_id';

