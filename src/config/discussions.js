/**
 * 讨论相关的前台轮询间隔。
 *
 * **两个场景分开设置**（2026-11-14 调整）：
 *
 *   1. `DISCUSSION_POLL_MS`（1 分钟）—— **讨论区页面**（`DiscussionsView`）用。
 *      用户正在看讨论区，就该尽快看到别人发的新消息，1 分钟是合理延迟。
 *
 *   2. `RECENT_POLL_MS`（30 分钟）—— **右栏「最新讨论」**（`App.vue`）用。
 *      右栏在**每个页面**都常驻，是请求量的主要来源：原来它与讨论区共用 1 分钟，
 *      意味着用户挂在任何页面不动，每小时都会打 60 次 `/api/recent`，
 *      Cloudflare Workers 每日 10 万次额度被快速消耗（2026-11-14 实测 13,890/天）。
 *      右栏只是「顺带看看最近有人说啥」，半小时刷新完全够用。
 *
 * **为什么以前共用**：怕两处间隔不同导致"右边出现了、中间还没有"的错位。
 * 但两者的**定位不同**：右侧是全局概览（慢无所谓），中间是正在读的列表（要快）。
 * 真出现短暂错位也能靠「切页 / 发表后立即刷新」兜住（`App.vue` 里那两个时机保留）。
 *
 * 调整这个值时请一起核对：
 *   - `docs/context/technical/COMMENTS_BACKEND.md` 的「讨论区中间的自动刷新」一节；
 *   - `scripts/dev/scratch/measure-poll-cadence.mjs`（实测真实间隔的脚本）。
 */
export const DISCUSSION_POLL_MS = 60000

/** 右栏「最新讨论」的轮询间隔：30 分钟（见上方说明，这是请求量最大来源） */
export const RECENT_POLL_MS = 1800000

/**
 * 评论列表**一页多少条**（也是讨论区首屏显示多少条）。
 *
 * 🔴 **这个值有两个消费者，必须一致**：
 *   1. 前端 `CommentsPanel` 拉列表时用的 `limit`；
 *   2. 服务端 `commentContext` 判断"这条评论是否在首屏里"（`inFirstPage`）——
 *      它用 `OFFSET COMMENT_PAGE_SIZE` 取首页边界来比较，避免 `COUNT(*)` 全表扫。
 *
 * 不一致的后果是**静默的**：服务端以为某条在首页里（不返回定位卡片），
 * 而列表里其实没有它 —— 用户点了「去看看」又变成"没反应"。
 * （2026-10-07 实际踩过：服务端写死 50、前端默认 20，第 21~50 条全被误判。）
 */
export const COMMENT_PAGE_SIZE = 20
