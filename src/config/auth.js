/**
 * 账号体系（注册 / 登录 / 改密码 / 换邮箱）—— **协议常量的唯一定义处**。
 *
 * ## 为什么单独抽一个 config
 *
 * 与 `config/emoticons.js` 同一个理由：**同一份口径被两端引用**。
 * - 前端 `src/utils/passwordKdf.js` 要用 KDF 参数；
 * - 服务端 `functions/api/[[path]].js` 要用验证码有效期、限流阈值、模板 ID。
 *
 * 如果两边各写一份常量，**改了一处忘了另一处**就是静默故障
 * （例如轮数不一致 → 用户注册能过、登录永远失败，而且看不出原因）。
 *
 * ## 本模块必须保持零依赖
 *
 * 服务端直接 import 它，**不要**在这里引入任何 `utils/env.js`、Vue、浏览器 API。
 * 它是一个纯常量模块，Node / workerd / 浏览器三处都能直接加载。
 *
 * 完整设计依据见 `docs/technical/ACCOUNT_SYSTEM.md`。
 */

// ============================================================
// 一、密码派生（客户端 KDF）
// ============================================================

/**
 * PBKDF2 迭代轮数。
 *
 * **600000 是 OWASP 对 PBKDF2-HMAC-SHA256 的推荐值**，这里如实采用。
 *
 * 为什么能取这么高：**这 60 万轮跑在用户自己的设备上**，不是 Worker。
 * workerd 对服务端 PBKDF2 有 **100000 轮硬封顶**（超了直接报错），
 * 而用户浏览器/手机**没有任何此类上限**。
 *
 * ⚠️ **这个值一旦上线就不能改**：它参与派生结果，改了等于
 * 所有已注册用户的密码全部失效。要升级只能走"记录 `pw_iters`、登录时按旧值校验、
 * 校验通过后自动重算为新值"的迁移路径（`users.pw_iters` 就是为此预留的）。
 */
export const PBKDF2_ITERS = 600000

/** PBKDF2 摘要算法。只用 SHA-256（不用 SHA-1，也不引入 argon2 —— Workers 不支持）。 */
export const PBKDF2_HASH = 'SHA-256'

/** 派生结果字节数。32 字节 = 256 位，输出为 **64 位小写 hex**。 */
export const PBKDF2_KEY_BYTES = 32

/**
 * ⚠️ **盐的编码约定（最容易出错的地方，改之前先读这段）**
 *
 * 服务端 `/api/auth/salt` 返回的是一个 **64 位 hex 字符串**。客户端**不做 hex 解码**，
 * 而是**把这个字符串本身的 UTF-8 字节直接当作 PBKDF2 的 salt**。
 *
 * ```js
 * // ✅ 我们的做法
 * saltBytes = new TextEncoder().encode(saltHex)   // 64 字节
 *
 * // ❌ 另一种看着也合理的做法（会造成两端不一致）
 * saltBytes = hexToBytes(saltHex)                 // 32 字节
 * ```
 *
 * **为什么选前者**：少一层转换就少一个出错的地方，而且 Node 与浏览器的
 * `TextEncoder` 行为完全一致。**两种做法都能用，但必须两端一致** ——
 * 所以这里用常量把它钉死，并由 `tests/ui/password-kdf.spec.js`
 * （真浏览器 vs Node 逐字节比对）守住。
 */
export const SALT_ENCODING = 'utf8-of-hex-string'

// ============================================================
// 二、邮箱验证码
// ============================================================

/** 验证码位数。6 位数字 = 100 万种可能。 */
export const CODE_DIGITS = 6

/** 验证码有效期：10 分钟。 */
export const CODE_TTL_MS = 10 * 60 * 1000

/**
 * 同一 (邮箱, 用途) 最多允许几个有效码**并存**。
 *
 * 为什么不是 1：**邮件到信时间是 3 秒 ~ 5 分钟**，用户等不及点重发时，
 * 两封邮件会**乱序到达**（新码先到、旧码后到）。若"重发即作废旧码"，
 * 用户打开先到的那封旧邮件输码会**无辜失败**。
 *
 * 为什么不是更多：并存越多，被穷举的面越大。3 个已经覆盖"重发一两次"的真实场景。
 */
export const CODE_MAX_ACTIVE = 3

/** 同一邮箱的重发冷却（秒）。 */
export const CODE_COOLDOWN_SEC = 60

/** 同一邮箱每天最多发几次验证码。 */
export const CODE_EMAIL_DAILY_MAX = 10

/** 验证码连续输错几次即整批作废、要求重新获取。 */
export const CODE_MAX_ATTEMPTS = 5

// ============================================================
// 三、限流（主防线是同邮箱，IP 只做兜底）
// ============================================================

/**
 * 同 IP 发码限流。
 *
 * ⚠️ **不要照搬评论接口的 `perHour: 5 / perDay: 20`**：那是"一个人发内容"的场景；
 * 而注册是**多人共用一个出口**（宿舍 / 公司 / 学校的 NAT）。
 * 阈值定成 5 次/小时会让**第 6 个真实用户被误伤** ——
 * 被刷只是浪费额度，**误伤是真人注册不了**，后者更糟。
 */
export const CODE_IP_HOURLY_MAX = 20
export const CODE_IP_DAILY_MAX = 100

/** 登录失败在 10 分钟窗口内允许的次数（账号维度 + IP 维度）。 */
export const LOGIN_MAX_FAILS = 5

// ============================================================
// 四、会话
// ============================================================

/**
 * 会话有效期：30 天，**滑动过期**（每次使用自动续期）。
 *
 * 滑动过期意味着"只要还在用就不会被踢"，比固定 30 天对用户友好得多，
 * 同时令牌本身 30 天不用就失效。
 */
export const SESSION_TTL_MS = 30 * 24 * 60 * 60 * 1000

// ============================================================
// 五、账号字段规则
// ============================================================

/** 昵称长度（**全站唯一**，先到先得）。 */
export const NICK_MIN = 2
export const NICK_MAX = 12

/**
 * 密码长度下限。
 *
 * ⚠️ **只能在**前端**校验** —— 服务端**根本收不到密码**，
 * 它收到的只是设备算出的 `verifier`。所以"拒绝弱口令"这道关卡是
 * **可被恶意客户端绕过的**，但绕过只影响攻击者自己的账号强度，不构成对他人的风险。
 */
export const PASSWORD_MIN = 8

/** 头像默认值：`at001_0` = 希尔（女主）。注册时不选就用它。 */
export const DEFAULT_AVATAR = 'at001_0'

// ============================================================
// 六、人机验证（蛋点选）
// ============================================================

/**
 * 人机验证形态：**照着找**。
 *
 * 提示区给 `CAPTCHA_PROMPT_COUNT` 张蛋图（**不带名字**），
 * 画布上放 `CAPTCHA_CANVAS_COUNT` 个蛋，用户**按顺序点中那几张**。
 *
 * - 画布不放名字：**少一个"脚本读文字就知道答案"的泄露点**；
 * - 错 1 次即整题作废（换新题），所以 `captchas` 表**不需要 attempts 计数**。
 */
export const CAPTCHA_PROMPT_COUNT = 3
export const CAPTCHA_CANVAS_COUNT = 5

/** 人机验证有效期：3 分钟（比邮箱验证码短，因为它只是一次交互）。 */
export const CAPTCHA_TTL_MS = 3 * 60 * 1000

/**
 * 蛋池只用 4 星与 5 星蛋（`pet-eggs.json` 的 `displayStar`）。
 *
 * ⚠️ **必须用 `displayStar` 而不是 `star`** —— 后者是内部值，
 * 32 个蛋**没有一个是两者相同的**（内部 1/2/3 对应显示 3/4/5）。
 * 星数是**我们自己画上去的**（蛋纹理里没有星星，游戏是另外渲染的）。
 */
export const CAPTCHA_EGG_MIN_STAR = 4

/** 盲猜成功率（仅用于注释与验收断言）：`1 / (5×4×3)` = 1/60 ≈ 1.7%。 */
export const CAPTCHA_BLIND_RATE = 1 / (CAPTCHA_CANVAS_COUNT * (CAPTCHA_CANVAS_COUNT - 1) * (CAPTCHA_CANVAS_COUNT - 2))

