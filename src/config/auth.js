/**
 * 验证码模板 ID。
 *
 * **换模板只改这一行**。为什么放代码常量而不是环境变量：两者改完**都要重新部署**，
 * 但常量**进版本库、可 review、可回溯**；环境变量在面板里改完就查不到历史了。
 * 模板 ID **不是秘密**，放常量更合适。
 *
 * 历史：`62664`（初版：浅色、无标题栏、虚线）→ **`62671`**（现行：深木标题栏 + 实线边框）。
 */
export const SES_TEMPLATE_ID = 62671

/** 地域。广州是为国内收件人选的（QQ / 163 实测进收件箱）。 */
export const SES_REGION = 'ap-guangzhou'

/** `FromEmailAddress` 的**完整格式**：别名 + 一个空格 + `<邮箱>`。 */
export const SES_FROM = '深渊大书院 <noreply@mail.yxzmy.top>'

/** 邮件主题。 */
export const SES_SUBJECT = '【深渊大书院】邮箱验证码'

/**
 * 模板变量名。
 *
 * ⚠️ **必须与腾讯云控制台里模板的 `{{变量名}}` 一一对应**。
 * 若改模板时动了变量名而没改这里，邮件会**静默地发出一个空白验证码**
 * —— 用户收到一封信，验证码位置是空的，而且没有任何报错。
 */
export const SES_VARS = Object.freeze({ code: 'code', minutes: 'minutes' })

/** 验证码在邮件里宣称的有效分钟数（与 `CODE_TTL_MS` 保持一致）。 */
export const SES_CODE_MINUTES = CODE_TTL_MS / 60000
