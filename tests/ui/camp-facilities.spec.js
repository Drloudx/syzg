test('research overview uses original game cards and linked branches on desktop and mobile', async ({ page }, testInfo) => {
  await page.goto('/#/facilities?facility=camp&mode=research&group=collect')
  await dismissGlobalModals(page)
  const camp = page.locator('.camp-panel')
  await expect(camp.locator('.research-node')).toHaveCount(9)
  await expect(camp.locator('.research-tree-lines path')).toHaveCount(8)
  await expect(camp.getByRole('combobox')).toHaveCount(0)
  await expect.poll(() => camp.locator('.research-node img').evaluateAll(images => images.every(image => image.complete && image.naturalWidth > 0))).toBe(true)
  expect(await camp.locator('.research-node').first().evaluate(element => getComputedStyle(element).backgroundImage)).toContain('build_tree_botm.webp')
  expect(await camp.evaluate(element => element.scrollWidth <= element.clientWidth + 1)).toBe(true)
  const root = camp.locator('[data-research="collect_tree"]')
  const diagram = camp.locator('.research-tree-scroll')
  const rootBox = await root.boundingBox()
  const diagramBox = await diagram.boundingBox()
  expect(rootBox.x).toBeGreaterThanOrEqual(diagramBox.x)
  expect(rootBox.x + rootBox.width).toBeLessThanOrEqual(diagramBox.x + diagramBox.width)
  // Dragging from a card pans the map without opening that research.
  await root.scrollIntoViewIfNeeded()
  const dragBox = await root.boundingBox()
  await page.mouse.move(dragBox.x + dragBox.width / 2, dragBox.y + dragBox.height / 2)
  await page.mouse.down()
  await page.mouse.move(dragBox.x + dragBox.width / 2 - 100, dragBox.y + dragBox.height / 2, { steps: 10 })
  await page.mouse.up()
  expect(await diagram.evaluate(element => element.scrollLeft)).toBeGreaterThan(80)
  await expect(camp.locator('.research-node')).toHaveCount(9)
  expect(await diagram.evaluate(element => getComputedStyle(element).scrollbarWidth)).toBe('none')
  await diagram.evaluate(element => { element.scrollLeft = 0 })
  await page.screenshot({ path: testInfo.outputPath('research-tree.png') })
  await camp.getByRole('button', { name: '采石技巧', exact: true }).click()
  await expect(camp.getByRole('heading', { name: '采石技巧', exact: true })).toBeVisible()
  await camp.getByRole('button', { name: '返回研究树', exact: true }).click()
  await camp.getByPlaceholder('搜索研究、效果或材料...').fill('铜矿鉴定')
  await expect(camp.locator('.camp-count .count-num')).toHaveText('1')
  await expect(camp.locator('.research-node:not(.is-context)')).toHaveCount(1)
  await expect(camp.locator('.research-node.is-context')).toHaveCount(3)
  await camp.getByRole('button', { name: '铜矿鉴定', exact: true }).click()
  await expect(camp.getByRole('heading', { name: '铜矿鉴定', exact: true })).toBeVisible()
})

test('malformed facility data shows an error without a blank camp page', async ({ page }) => {
  await page.route('**/data/parsed/facilities.json*', route => route.fulfill({ contentType: 'application/json', body: JSON.stringify([{ key: 'camp', name: '营地' }]) }))
  await page.goto('/#/facilities?facility=camp&mode=research')
  await dismissGlobalModals(page)
  await expect(page.getByText(/加载失败：.*数据格式不完整/)).toBeVisible()
  await expect(page.getByText('正在整理设施数据...', { exact: true })).toHaveCount(0)
  const filter = page.locator('.facilities-page > .filter-panel')
  await expect(filter.getByRole('tab')).toHaveCount(3)
  await expect(filter.getByPlaceholder('搜索研究、效果或材料...')).toBeVisible()
})

