import { expect, test } from '@playwright/test'

const dismissGlobalModals = async page => {
  for (let attempt = 0; attempt < 10; attempt += 1) {
    const close = page.locator('.ui-modal-overlay.is-teleported .ui-modal-close:visible').first()
    if (!await close.count()) return
    await close.click()
    await page.waitForTimeout(100)
  }
}

test('camp upgrade deep links show source-level rewards, materials, and terminal state', async ({ page }, testInfo) => {
  await page.goto('/#/facilities?facility=camp&mode=building&building=center&level=1')
  await dismissGlobalModals(page)
  const camp = page.locator('.camp-panel')
  await expect(camp.getByRole('heading', { name: '营地中心', exact: true })).toBeVisible()
  await expect(camp.getByRole('heading', { name: '1级 → 2级' })).toBeVisible()
  await expect(camp.getByRole('heading', { name: '升级奖励', exact: true })).toBeVisible()
  await expect(camp.locator('.camp-building-choice')).toHaveCount(7)
  await page.screenshot({ path: testInfo.outputPath('camp-building-top.png') })
  const firstReward = camp.locator('.camp-materials').filter({ has: page.getByRole('heading', { name: '升级奖励', exact: true }) }).locator('.ui-reward-card').first()
  await firstReward.click()
  await expect(page).toHaveURL(/itemId=item_50004/)
  const modal = page.locator('.app-main > .ui-modal-host .ui-modal-overlay')
  await expect(modal).toBeVisible()
  await modal.locator('.ui-modal-close').click()
  await expect(page).not.toHaveURL(/itemId=/)
  await expect(camp.getByRole('heading', { name: '1级 → 2级' })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('camp-building.png'), fullPage: true })

  await camp.getByRole('button', { name: '7级', exact: true }).click()
  await expect(camp.getByRole('heading', { name: '7级 · 满级' })).toBeVisible()
  await expect(camp.getByRole('heading', { name: '升级消耗', exact: true })).toHaveCount(0)
  await camp.getByRole('button', { name: '料理台', exact: true }).click()
  await camp.getByRole('button', { name: '3级', exact: true }).click()
  await expect(camp.locator('.ui-info-row').filter({ hasText: '生命值' }).first()).toContainText('+1000')
})

